def test_2(dot_v):
    print("Testing: ", end = "")
    inception = Series([0.63, 0.92, 0.44], index=['drama', 'thriller', 'comedy']).astype("float64")
    u13 = Series([0.75, 0.75, 0.29], index=['drama', 'thriller', 'comedy']).astype("float64")
    answer = dot_v(inception, u13)
    assert isinstance(answer, (np.floating, float)), "Expected output of dot_v() to be a float"
    assert 1.2809 < answer < 1.2903, "Expected dot_v for inception and user 13 to yield a value around 1.29"
    
    v1 = Series([0.1, 0.2, 0.3, 0.4])
    v2 = Series([1, 2, 3, 4])
    assert 2.99 < dot_v(v1, v2) < 3.01, "Vectors of size 4 not correctly computed"
    print("success!")
    
    
